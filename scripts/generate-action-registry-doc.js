'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { ACTION_REGISTRY, ACTION_VERSION } = require('../public/js/action-registry');

const output = path.resolve(__dirname, '..', 'docs', 'action-registry.md');
const escapeCell = (value) => String(value == null || value === '' ? '—' : value).replaceAll('|', '\\|').replaceAll('\n', ' ');
const rows = ACTION_REGISTRY.map((action) => [
  action.action_id,
  action.label,
  action.entity,
  action.placement,
  action.variant,
  action.permission,
  action.backend_action,
  action.mutation ? action.idempotency.header : '—',
  action.event,
]);

const content = [
  '# Action registry',
  '',
  `Generated from \`public/js/action-registry.js\` (version ${ACTION_VERSION}). Do not edit this file by hand.`,
  '',
  '| Action ID | Label | Entity | Placement | Variant | Permission | Backend action | Idempotency | Audit event |',
  '|---|---|---|---|---|---|---|---|---|',
  ...rows.map((row) => `| ${row.map(escapeCell).join(' | ')} |`),
  '',
].join('\n');

fs.writeFileSync(output, content, 'utf8');
console.log(path.relative(process.cwd(), output));
